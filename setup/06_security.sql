/*
 * 06_security.sql
 * Security model with Restricted Caller's Rights (RCR).
 *
 * The Streamlit app runs stored procedures that execute with the OWNER's
 * privileges, not the caller's. End users get the app role which has
 * USAGE on the procedures but NO direct table access.
 */

USE ROLE ACCOUNTADMIN;

-- Create the application role (owns the RCR procedures)
CREATE ROLE IF NOT EXISTS DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON DATABASE HEALTHCARE_DW TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.BILLING TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DRUG_INTERACTION_APP_ROLE;

-- Grant table access to the app role (NOT to end users)
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.BILLING TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;

-- Create the end-user role (NO direct table access)
CREATE ROLE IF NOT EXISTS DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON DATABASE HEALTHCARE_DW TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE DRUG_INTERACTION_USER_ROLE;

-- RCR Stored Procedure: Get patient interaction alerts
-- Runs with OWNER (APP_ROLE) privileges, callable by USER_ROLE
CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.PHARMACY.GET_PATIENT_ALERTS(P_PATIENT_ID NUMBER)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS OWNER   -- << Restricted Caller's Rights
AS
BEGIN
    LET rs RESULTSET := (
        SELECT
            DRUG_A_NAME,
            DRUG_B_NAME,
            SEVERITY,
            CLINICAL_EFFECT,
            MANAGEMENT,
            PATIENT_SUMMARY,
            ALTERNATIVE_FOR_A,
            ALTERNATIVE_FOR_B,
            PRESCRIBER_A_NAME,
            PRESCRIBER_B_NAME
        FROM HEALTHCARE_DW.PHARMACY.PATIENT_DRUG_INTERACTION_ALERTS
        WHERE PATIENT_ID = :P_PATIENT_ID
        ORDER BY
            CASE SEVERITY
                WHEN 'CRITICAL' THEN 1
                WHEN 'HIGH' THEN 2
                WHEN 'MODERATE' THEN 3
                ELSE 4
            END
    );
    RETURN TABLE(rs);
END;

-- RCR Stored Procedure: Get provider's patient panel with alerts
CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.PHARMACY.GET_PROVIDER_PANEL(P_PROVIDER_ID NUMBER)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS OWNER
AS
BEGIN
    LET rs RESULTSET := (
        SELECT
            a.PATIENT_ID,
            a.FIRST_NAME,
            a.LAST_NAME,
            a.SEVERITY,
            a.DRUG_A_NAME,
            a.DRUG_B_NAME,
            a.CLINICAL_EFFECT,
            a.MANAGEMENT,
            a.ALTERNATIVE_FOR_A,
            a.ALTERNATIVE_FOR_B,
            a.PREFERRED_LANGUAGE
        FROM HEALTHCARE_DW.PHARMACY.PATIENT_DRUG_INTERACTION_ALERTS a
        WHERE a.PRESCRIBER_A_ID = :P_PROVIDER_ID
           OR a.PRESCRIBER_B_ID = :P_PROVIDER_ID
        ORDER BY
            CASE a.SEVERITY
                WHEN 'CRITICAL' THEN 1
                WHEN 'HIGH' THEN 2
                WHEN 'MODERATE' THEN 3
                ELSE 4
            END,
            a.LAST_NAME, a.FIRST_NAME
    );
    RETURN TABLE(rs);
END;

-- RCR Stored Procedure: Get translated patient summary
CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.PHARMACY.GET_TRANSLATED_ALERT(
    P_PATIENT_ID NUMBER,
    P_INTERACTION_ID NUMBER
)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS OWNER
AS
BEGIN
    LET rs RESULTSET := (
        SELECT
            a.DRUG_A_NAME,
            a.DRUG_B_NAME,
            a.SEVERITY,
            a.PREFERRED_LANGUAGE,
            a.PATIENT_SUMMARY AS ORIGINAL_SUMMARY,
            CASE
                WHEN a.PREFERRED_LANGUAGE = 'en' THEN a.PATIENT_SUMMARY
                ELSE SNOWFLAKE.CORTEX.TRANSLATE(
                    a.PATIENT_SUMMARY,
                    'en',
                    a.PREFERRED_LANGUAGE
                )
            END AS TRANSLATED_SUMMARY,
            CASE
                WHEN a.PREFERRED_LANGUAGE = 'en' THEN a.MANAGEMENT
                ELSE SNOWFLAKE.CORTEX.TRANSLATE(
                    a.MANAGEMENT,
                    'en',
                    a.PREFERRED_LANGUAGE
                )
            END AS TRANSLATED_MANAGEMENT
        FROM HEALTHCARE_DW.PHARMACY.PATIENT_DRUG_INTERACTION_ALERTS a
        WHERE a.PATIENT_ID = :P_PATIENT_ID
          AND a.INTERACTION_ID = :P_INTERACTION_ID
    );
    RETURN TABLE(rs);
END;

-- Grant USAGE on procedures to end-user role (they can call but not see underlying tables)
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.PHARMACY.GET_PATIENT_ALERTS(NUMBER)
  TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.PHARMACY.GET_PROVIDER_PANEL(NUMBER)
  TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.PHARMACY.GET_TRANSLATED_ALERT(NUMBER, NUMBER)
  TO ROLE DRUG_INTERACTION_USER_ROLE;

-- Grant the app role to the user role hierarchy
GRANT ROLE DRUG_INTERACTION_USER_ROLE TO ROLE SYSADMIN;
GRANT ROLE DRUG_INTERACTION_APP_ROLE TO ROLE SYSADMIN;
