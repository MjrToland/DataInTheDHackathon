/*
 * 06_security.sql
 * Restricted Caller's Rights (RCR) security model.
 *
 * Pattern:
 *   End User (DRUG_INTERACTION_USER_ROLE) -> CALL procedure (has USAGE)
 *   -> RCR Procedure (EXECUTE AS RESTRICTED CALLER, owned by APP_ROLE)
 *   -> Underlying tables (caller grants allow SELECT through APP_ROLE)
 */

-- Create roles
CREATE ROLE IF NOT EXISTS DRUG_INTERACTION_APP_ROLE;
CREATE ROLE IF NOT EXISTS DRUG_INTERACTION_USER_ROLE;

-- App role: database/schema/table access
GRANT USAGE ON DATABASE HEALTHCARE_DW TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE DRUG_INTERACTION_APP_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;

-- User role: minimal access (schema usage, procedure usage, no tables)
GRANT USAGE ON DATABASE HEALTHCARE_DW TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE DRUG_INTERACTION_USER_ROLE;

-- RCR Stored Procedures (owned by APP_ROLE)
CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PATIENT_ALERTS(P_PATIENT_ID NUMBER)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS RESTRICTED CALLER
AS
$$
BEGIN
    LET rs RESULTSET := (
        SELECT DRUG_A_NAME, DRUG_B_NAME, SEVERITY, CLINICAL_EFFECT,
               MANAGEMENT, PATIENT_SUMMARY, ALTERNATIVE_FOR_A, ALTERNATIVE_FOR_B,
               PRESCRIBER_A_NAME, PRESCRIBER_B_NAME
        FROM HEALTHCARE_DW.DDI_APP.PATIENT_DRUG_INTERACTION_ALERTS
        WHERE PATIENT_ID = :P_PATIENT_ID
        ORDER BY CASE SEVERITY WHEN 'CRITICAL' THEN 1 WHEN 'HIGH' THEN 2 WHEN 'MODERATE' THEN 3 ELSE 4 END
    );
    RETURN TABLE(rs);
END;
$$;

CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PROVIDER_PANEL(P_PROVIDER_ID NUMBER)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS RESTRICTED CALLER
AS
$$
BEGIN
    LET rs RESULTSET := (
        SELECT a.PATIENT_ID, a.FIRST_NAME, a.LAST_NAME, a.SEVERITY,
               a.DRUG_A_NAME, a.DRUG_B_NAME, a.CLINICAL_EFFECT, a.MANAGEMENT,
               a.ALTERNATIVE_FOR_A, a.ALTERNATIVE_FOR_B, a.PREFERRED_LANGUAGE
        FROM HEALTHCARE_DW.DDI_APP.PATIENT_DRUG_INTERACTION_ALERTS a
        WHERE a.PRESCRIBER_A_ID = :P_PROVIDER_ID OR a.PRESCRIBER_B_ID = :P_PROVIDER_ID
        ORDER BY CASE a.SEVERITY WHEN 'CRITICAL' THEN 1 WHEN 'HIGH' THEN 2 WHEN 'MODERATE' THEN 3 ELSE 4 END,
                 a.LAST_NAME, a.FIRST_NAME
    );
    RETURN TABLE(rs);
END;
$$;

CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.DDI_APP.GET_TRANSLATED_ALERT(
    P_PATIENT_ID NUMBER, P_INTERACTION_ID NUMBER)
RETURNS TABLE()
LANGUAGE SQL
EXECUTE AS RESTRICTED CALLER
AS
$$
BEGIN
    LET rs RESULTSET := (
        SELECT a.DRUG_A_NAME, a.DRUG_B_NAME, a.SEVERITY, a.PREFERRED_LANGUAGE,
               a.PATIENT_SUMMARY AS ORIGINAL_SUMMARY,
               CASE WHEN a.PREFERRED_LANGUAGE = 'en' THEN a.PATIENT_SUMMARY
                    ELSE AI_TRANSLATE(a.PATIENT_SUMMARY, 'en', a.PREFERRED_LANGUAGE) END AS TRANSLATED_SUMMARY,
               CASE WHEN a.PREFERRED_LANGUAGE = 'en' THEN a.MANAGEMENT
                    ELSE AI_TRANSLATE(a.MANAGEMENT, 'en', a.PREFERRED_LANGUAGE) END AS TRANSLATED_MANAGEMENT
        FROM HEALTHCARE_DW.DDI_APP.PATIENT_DRUG_INTERACTION_ALERTS a
        WHERE a.PATIENT_ID = :P_PATIENT_ID AND a.INTERACTION_ID = :P_INTERACTION_ID
    );
    RETURN TABLE(rs);
END;
$$;

-- Transfer ownership to app role
GRANT OWNERSHIP ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PATIENT_ALERTS(NUMBER) TO ROLE DRUG_INTERACTION_APP_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PROVIDER_PANEL(NUMBER) TO ROLE DRUG_INTERACTION_APP_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_TRANSLATED_ALERT(NUMBER, NUMBER) TO ROLE DRUG_INTERACTION_APP_ROLE COPY CURRENT GRANTS;

-- Caller grants: allow RCR procedures to use caller's privileges
GRANT CALLER USAGE ON DATABASE HEALTHCARE_DW TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT CALLER USAGE ON SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT CALLER USAGE ON SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT CALLER USAGE ON SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT CALLER USAGE ON SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT INHERITED CALLER SELECT ON ALL VIEWS IN SCHEMA HEALTHCARE_DW.DDI_APP TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CORE TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.PHARMACY TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT INHERITED CALLER SELECT ON ALL TABLES IN SCHEMA HEALTHCARE_DW.CLINICAL TO ROLE DRUG_INTERACTION_APP_ROLE;
GRANT CALLER USAGE ON WAREHOUSE DEFAULT_WH TO ROLE DRUG_INTERACTION_APP_ROLE;

-- Grant procedure USAGE to user role
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PATIENT_ALERTS(NUMBER) TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_PROVIDER_PANEL(NUMBER) TO ROLE DRUG_INTERACTION_USER_ROLE;
GRANT USAGE ON PROCEDURE HEALTHCARE_DW.DDI_APP.GET_TRANSLATED_ALERT(NUMBER, NUMBER) TO ROLE DRUG_INTERACTION_USER_ROLE;

-- Role hierarchy
GRANT ROLE DRUG_INTERACTION_USER_ROLE TO ROLE ATTENDEE_ROLE;
GRANT ROLE DRUG_INTERACTION_APP_ROLE TO ROLE ATTENDEE_ROLE;
