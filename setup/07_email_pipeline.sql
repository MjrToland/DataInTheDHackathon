-- Stored procedure: Generate and log email alerts for new interactions
CREATE OR REPLACE PROCEDURE HEALTHCARE_DW.PHARMACY.GENERATE_INTERACTION_ALERTS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
BEGIN
    -- Find CRITICAL and HIGH interactions not yet emailed
    INSERT INTO HEALTHCARE_DW.PHARMACY.ALERT_EMAIL_LOG
        (PATIENT_ID, INTERACTION_ID, PROVIDER_ID, PROVIDER_NAME,
         SEVERITY, EMAIL_SUBJECT, EMAIL_BODY)
    SELECT
        a.PATIENT_ID,
        a.INTERACTION_ID,
        a.PRESCRIBER_A_ID AS PROVIDER_ID,
        a.PRESCRIBER_A_NAME AS PROVIDER_NAME,
        a.SEVERITY,
        -- Email subject
        CONCAT(
            '[', a.SEVERITY, ' ALERT] Drug Interaction: ',
            a.DRUG_A_NAME, ' + ', a.DRUG_B_NAME,
            ' — Patient: ', a.LAST_NAME, ', ', a.FIRST_NAME
        ) AS EMAIL_SUBJECT,
        -- Email body generated by AI
        SNOWFLAKE.CORTEX.COMPLETE(
            'claude-3-5-sonnet',
            CONCAT(
                'Write a brief professional email to a healthcare provider about a drug interaction alert. ',
                'Provider: ', a.PRESCRIBER_A_NAME, ' (', a.PRESCRIBER_A_SPECIALTY, '). ',
                'Patient: ', a.FIRST_NAME, ' ', a.LAST_NAME, ' (DOB: ', a.DATE_OF_BIRTH, '). ',
                'Drug A: ', a.DRUG_A_NAME, ' prescribed on ', a.RX_A_DATE, '. ',
                'Drug B: ', a.DRUG_B_NAME, ' prescribed by ', a.PRESCRIBER_B_NAME,
                ' (', a.PRESCRIBER_B_SPECIALTY, ') on ', a.RX_B_DATE, '. ',
                'Severity: ', a.SEVERITY, '. ',
                'Interaction: ', a.CLINICAL_EFFECT, '. ',
                'Management: ', a.MANAGEMENT, '. ',
                'Alternative for ', a.DRUG_A_NAME, ': ', a.ALTERNATIVE_FOR_A, '. ',
                'Alternative for ', a.DRUG_B_NAME, ': ', a.ALTERNATIVE_FOR_B, '. ',
                'Format as a professional medical alert email with subject line, body, and recommended action. ',
                'Keep it concise — 3-4 paragraphs max.'
            )
        ) AS EMAIL_BODY
    FROM HEALTHCARE_DW.PHARMACY.PATIENT_DRUG_INTERACTION_ALERTS a
    WHERE a.SEVERITY IN ('CRITICAL', 'HIGH')
      AND NOT EXISTS (
          SELECT 1 FROM HEALTHCARE_DW.PHARMACY.ALERT_EMAIL_LOG log
          WHERE log.PATIENT_ID = a.PATIENT_ID
            AND log.INTERACTION_ID = a.INTERACTION_ID
            AND log.PROVIDER_ID = a.PRESCRIBER_A_ID
      );

    -- Also alert Prescriber B if different from Prescriber A
    INSERT INTO HEALTHCARE_DW.PHARMACY.ALERT_EMAIL_LOG
        (PATIENT_ID, INTERACTION_ID, PROVIDER_ID, PROVIDER_NAME,
         SEVERITY, EMAIL_SUBJECT, EMAIL_BODY)
    SELECT
        a.PATIENT_ID,
        a.INTERACTION_ID,
        a.PRESCRIBER_B_ID AS PROVIDER_ID,
        a.PRESCRIBER_B_NAME AS PROVIDER_NAME,
        a.SEVERITY,
        CONCAT(
            '[', a.SEVERITY, ' ALERT] Drug Interaction: ',
            a.DRUG_A_NAME, ' + ', a.DRUG_B_NAME,
            ' — Patient: ', a.LAST_NAME, ', ', a.FIRST_NAME
        ),
        SNOWFLAKE.CORTEX.COMPLETE(
            'claude-3-5-sonnet',
            CONCAT(
                'Write a brief professional email to a healthcare provider about a drug interaction alert. ',
                'Provider: ', a.PRESCRIBER_B_NAME, ' (', a.PRESCRIBER_B_SPECIALTY, '). ',
                'Patient: ', a.FIRST_NAME, ' ', a.LAST_NAME, ' (DOB: ', a.DATE_OF_BIRTH, '). ',
                'Drug A: ', a.DRUG_A_NAME, ' prescribed by ', a.PRESCRIBER_A_NAME, '. ',
                'Drug B: ', a.DRUG_B_NAME, ' prescribed on ', a.RX_B_DATE, '. ',
                'Severity: ', a.SEVERITY, '. ',
                'Interaction: ', a.CLINICAL_EFFECT, '. ',
                'Management: ', a.MANAGEMENT, '. ',
                'Alternative for ', a.DRUG_A_NAME, ': ', a.ALTERNATIVE_FOR_A, '. ',
                'Alternative for ', a.DRUG_B_NAME, ': ', a.ALTERNATIVE_FOR_B, '. ',
                'Format as a professional medical alert email. Keep it concise — 3-4 paragraphs max.'
            )
        )
    FROM HEALTHCARE_DW.PHARMACY.PATIENT_DRUG_INTERACTION_ALERTS a
    WHERE a.SEVERITY IN ('CRITICAL', 'HIGH')
      AND a.PRESCRIBER_B_ID != a.PRESCRIBER_A_ID
      AND NOT EXISTS (
          SELECT 1 FROM HEALTHCARE_DW.PHARMACY.ALERT_EMAIL_LOG log
          WHERE log.PATIENT_ID = a.PATIENT_ID
            AND log.INTERACTION_ID = a.INTERACTION_ID
            AND log.PROVIDER_ID = a.PRESCRIBER_B_ID
      );

    RETURN 'Alert generation complete';
END;

-- Scheduled task: run alert generation every 6 hours
CREATE OR REPLACE TASK HEALTHCARE_DW.PHARMACY.DRUG_INTERACTION_ALERT_TASK
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 */6 * * * America/Detroit'
  COMMENT = 'Generates email alerts for new CRITICAL and HIGH drug interactions'
AS
  CALL HEALTHCARE_DW.PHARMACY.GENERATE_INTERACTION_ALERTS();

-- Enable the task
ALTER TASK HEALTHCARE_DW.PHARMACY.DRUG_INTERACTION_ALERT_TASK RESUME;
