/*
 * 07_email_pipeline.sql
 * Automated email alerting pipeline for drug interactions.
 *
 * Pipeline flow:
 *   1. Scheduled Task runs every 6 hours
 *   2. Queries for new CRITICAL/HIGH severity interactions
 *   3. Generates translated email content using AI_COMPLETE + AI_TRANSLATE
 *   4. Sends email to prescribing providers via notification integration
 */

USE DATABASE HEALTHCARE_DW;
USE SCHEMA PHARMACY;

-- Tracking table: which alerts have been emailed
CREATE OR REPLACE TABLE HEALTHCARE_DW.PHARMACY.ALERT_EMAIL_LOG (
    LOG_ID               NUMBER AUTOINCREMENT,
    PATIENT_ID           NUMBER,
    INTERACTION_ID       NUMBER,
    PROVIDER_ID          NUMBER,
    PROVIDER_NAME        VARCHAR,
    SEVERITY             VARCHAR,
    EMAIL_SUBJECT        VARCHAR,
    EMAIL_BODY           VARCHAR,
    SENT_AT              TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    STATUS               VARCHAR DEFAULT 'SENT'
);

